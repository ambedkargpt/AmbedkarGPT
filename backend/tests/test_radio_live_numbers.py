"""Figures in a Hindi line are spelled out before the voice reads them."""
import pytest

from backend.worker.radio_live.numbers import cardinal, spell_out


@pytest.mark.parametrize("n, words", [
    (0, "शून्य"),
    (26, "छब्बीस"),
    (100, "एक सौ"),
    (2026, "दो हज़ार छब्बीस"),
    (4432, "चार हज़ार चार सौ बत्तीस"),
    (34651, "चौंतीस हज़ार छह सौ इक्यावन"),
    (100000, "एक लाख"),
    (356000, "तीन लाख छप्पन हज़ार"),
    (12000000, "एक करोड़ बीस लाख"),
    (1200000000, "एक सौ बीस करोड़"),
])
def test_cardinal(n, words):
    assert cardinal(n) == words


@pytest.mark.parametrize("line, said", [
    ("साल 2026 में", "साल दो हज़ार छब्बीस में"),
    ("1947 में आज़ादी", "उन्नीस सौ सैंतालीस में आज़ादी"),
    ("4,432 करोड़ रुपये", "चार हज़ार चार सौ बत्तीस करोड़ रुपये"),
    ("1,00,000 लोग", "एक लाख लोग"),
    ("नीति 2025-2032 के तहत", "नीति दो हज़ार पच्चीस से दो हज़ार बत्तीस के तहत"),
    ("नीति 2025 से 2032 के तहत", "नीति दो हज़ार पच्चीस से दो हज़ार बत्तीस के तहत"),
    ("12% बढ़ा", "बारह प्रतिशत बढ़ा"),
    ("3.5 लाख", "तीन दशमलव पाँच लाख"),
    ("मार्च 2024 में, और", "मार्च दो हज़ार चौबीस में, और"),
    ("२०२६ में", "दो हज़ार छब्बीस में"),
    ("G20 और COVID19", "G20 और COVID19"),
    ("कोई अंक नहीं", "कोई अंक नहीं"),
])
def test_spell_out(line, said):
    assert spell_out(line) == said
